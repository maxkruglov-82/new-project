import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {mock} from 'node:test';
import {PineTS} from '../new-project-2/node_modules/pinets/dist/pinets.min.es.js';
const root=new URL('../',import.meta.url);
const raw=JSON.parse(readFileSync(new URL('new-project-2/drafts/bag-ab-2026-10-23/candles-six-months.json',root))).candles;
const source=readFileSync(new URL('KRYTES_v72_REVERSAL_UPDATED.txt',root),'utf8');
mock.timers.enable({apis:['Date'],now:Date.parse('2026-10-24T00:00:00+07:00')});
async function check(day){
 const start=Date.parse(`2026-10-${day}T14:00:00+07:00`),end=start+86400000;
 const data=raw.filter(b=>b.time*1000>=start&&b.time*1000<end).map(b=>({openTime:b.time*1000,closeTime:b.time*1000+299999,open:b.open,high:b.high,low:b.low,close:b.close,volume:b.vol}));
 assert.ok(data.length>=120,'historical session candles must exist');
 mock.timers.setTime(end+1000);
 const ctx=await new PineTS(data,'SOLUSDT','5').run(source);
 const v=(n,i)=>ctx.plots[n].data[i].value;
 const entries=data.flatMap((b,i)=>v('LONG',i)||v('SHORT',i)?[{side:v('LONG',i)?'LONG':'SHORT',time:new Date(b.openTime+7*3600000).toISOString().slice(0,16),entry:v(v('LONG',i)?'LONG Entry':'SHORT Entry',i),multiplier:v('Position Multiplier',i),stop:v(v('LONG',i)?'LONG Stop':'SHORT Stop',i),target:v(v('LONG',i)?'LONG Target':'SHORT Target',i)}]:[]);
 return {entries,ctx,data};
}
const oct21=await check('21');
assert.equal(oct21.entries.length,1,'21 October: exactly one entry');
const e=oct21.entries[0];
assert.equal(e.side,'LONG');
assert.equal(e.time,'2026-10-21T20:30');
assert.equal(e.multiplier,1,'no doubled position after a false SHORT');
assert.ok(Math.abs(e.entry-106.81)<1e-8);
assert.ok(Math.abs(e.stop-105.91)<1e-8);
assert.ok(Math.abs(e.target-107.71)<1e-8);
const oct22=await check('22');
assert.equal(oct22.entries.length,1,'22 October: preserve the reviewed setup');
assert.equal(oct22.entries[0].side,'SHORT');
assert.equal(oct22.entries[0].time,'2026-10-22T19:15');
console.log(JSON.stringify({oct21:{candles:oct21.data.length,entries:oct21.entries},oct22:{candles:oct22.data.length,entries:oct22.entries}},null,2));
const oct16=await check('16');
assert.equal(oct16.entries.length,1,'16 October: exactly one confirmed setup');
assert.equal(oct16.entries[0].side,'SHORT','failed upper breakout followed by confirmed lower break');
assert.equal(oct16.entries[0].time,'2026-10-16T21:15','retest after 20:30 is now allowed');
assert.equal(oct16.entries[0].multiplier,1);
assert.ok(Math.abs(oct16.entries[0].stop-107.39)<1e-8);
assert.ok(Math.abs(oct16.entries[0].target-104.93)<1e-8);
console.log(JSON.stringify({oct16:{candles:oct16.data.length,entries:oct16.entries}},null,2));
