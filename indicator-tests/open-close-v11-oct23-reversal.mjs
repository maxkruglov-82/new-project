import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PineTS} from '../new-project-2/node_modules/pinets/dist/pinets.min.es.js';
const f=JSON.parse(readFileSync(new URL('./fixtures/mexc-sol-usdt-m5-2026-10-23-structure-reversal.json',import.meta.url)));
const data=f.candles.map(b=>({...b,volume:b.vol,openTime:b.time*1000,closeTime:b.time*1000+299999}));
const source=readFileSync(new URL('../KRYTES_V1_1_LONDON.txt',import.meta.url),'utf8');
const c=await new PineTS(data,'SOLUSDT','5').run(source+'\nplot(unfilledReversePlan?1:0,"ReversePlan")\nplot(str.contains(label.get_text(positionInfo),"Отменён без входа LONG")?1:0,"CancelledLongShown")');
const at=t=>data.findIndex(b=>b.openTime===Date.parse('2026-10-23T'+t+':00+07:00'));
const v=(n,t)=>c.plots[n].data[at(t)].value;
assert.equal(v('Состояние позиции','18:00'),7);
assert.equal(v('ReversePlan','19:55'),0,'no future swing confirmation');
assert.equal(v('ReversePlan','20:00'),1,'earlier single close remains valid after pivot confirmation');
assert.equal(v('Состояние позиции','20:00'),1);
assert.equal(v('Стоп позиции','20:00'),104.23);
assert.equal(v('Цель позиции','20:00'),104.63);
assert.equal(v('Граница RR 1:1','20:00'),104.43);
assert.equal(v('Состояние позиции','20:05'),5,'stop before a qualifying entry cancels the pending plan');
assert.equal(v('CancelledLongShown','20:05'),1);
assert.equal(v('CancelledLongShown','23:55'),1,'cancelled opposite plan remains visible in history');
assert.equal(v('Входов за день','23:55'),0);
assert.ok(c.plots['Вход LONG/SHORT'].data.every(b=>b.value===0));
console.log('PASS real MEXC Oct23: remembered single close, no future pivot, visible LONG plan, cancelled without a fill');
